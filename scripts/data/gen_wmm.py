"""Converts the World Magnetic Model coefficient file (WMM.COF) into
src/core/geo/wmm_data.cpp used by core/geo (FR-GEO-05), and optionally the official test
values into tests/fixtures/geo/wmm_test_values.csv.

Source: NOAA NCEI / British Geological Survey, WMM2025COF.zip from
  https://www.ncei.noaa.gov/products/world-magnetic-model/wmm-coefficients
(public domain, U.S. Government work).

Usage: gen_wmm.py WMM.COF src/core/geo/wmm_data.cpp [WMM2025_TestValues.txt test_values.csv]
"""
import sys

MAX_DEGREE = 12

# The SPDX header of the generated file (kept out of this script's own REUSE information).
# REUSE-IgnoreStart
HEADER = ("// SPDX-FileCopyrightText: 2026 Juan Maria Gomez Lopez "
          "<juan-maria.gomez-lopez@tutamail.com>\n"
          "// SPDX-License-Identifier: MIT\n")
# REUSE-IgnoreEnd


def read_coefficients(source):
    with open(source, encoding="ascii") as f:
        header = f.readline().split()
        epoch = float(header[0])
        name = header[1]
        released = header[2]
        terms = []
        for line in f:
            parts = line.split()
            if not parts or parts[0].startswith("9999"):
                break
            n, m = int(parts[0]), int(parts[1])
            g, h, gdot, hdot = (float(x) for x in parts[2:6])
            if not (1 <= n <= MAX_DEGREE and 0 <= m <= n):
                raise ValueError(f"unexpected term n={n} m={m}")
            terms.append((n, m, g, h, gdot, hdot))
    expected = MAX_DEGREE * (MAX_DEGREE + 3) // 2
    if len(terms) != expected:
        raise ValueError(f"expected {expected} terms, found {len(terms)}")
    return epoch, name, released, terms


def write_data(target, epoch, name, released, terms):
    with open(target, "w", newline="\n") as out:
        out.write(HEADER)
        out.write(
            "//\n"
            "// Generated by scripts/data/gen_wmm.py — do not edit.\n"
            f"// Gauss coefficients of the World Magnetic Model {name} (released {released}),\n"
            "// NOAA National Centers for Environmental Information and British Geological\n"
            "// Survey. U.S. Government material, not subject to copyright protection in the\n"
            "// United States (17 U.S.C. 105, 403).\n\n"
            '#include "wmm_data.hpp"\n\n'
            "namespace ds::geo::detail {\n\n"
            f'const char* const kWmmName = "{name}";\n'
            f"const double kWmmEpoch = {epoch:.1f};\n\n"
            "// {n, m, g, h, dg/dt, dh/dt}: nT and nT/year.\n"
            "// clang-format off\n"
            f"const std::array<WmmTerm, {len(terms)}> kWmmTerms = {{{{\n")
        for n, m, g, h, gdot, hdot in terms:
            out.write(f"    {{{n}, {m}, {g:.1f}, {h:.1f}, {gdot:.1f}, {hdot:.1f}}},\n")
        out.write("}};\n// clang-format on\n\n}  // namespace ds::geo::detail\n")
    print(f"wrote {len(terms)} terms ({name}, epoch {epoch}) to {target}")


def write_test_values(source, target):
    rows = []
    with open(source, encoding="ascii") as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            v = line.split()
            # year, alt km, lat, lon, D, I, H, X, Y, Z, F
            rows.append(v[:11])
    with open(target, "w", newline="\n") as out:
        out.write("# Official WMM2025 test values (NOAA NCEI / BGS, WMM2025_TestValues.txt),\n"
                  "# converted by scripts/data/gen_wmm.py. Height above the WGS84 ellipsoid.\n")
        out.write("year,height_km,lat_deg,lon_deg,decl_deg,incl_deg,h_nt,x_nt,y_nt,z_nt,f_nt\n")
        for r in rows:
            out.write(",".join(r) + "\n")
    print(f"wrote {len(rows)} test values to {target}")


def main(argv):
    if len(argv) not in (3, 5):
        sys.exit(__doc__)
    epoch, name, released, terms = read_coefficients(argv[1])
    write_data(argv[2], epoch, name, released, terms)
    if len(argv) == 5:
        write_test_values(argv[3], argv[4])


if __name__ == "__main__":
    main(sys.argv)
