"""Generates the coefficient tables of core/astro from their published sources.

  VSOP87D.ear  — VSOP87 (Bretagnon & Francou 1988), version D: heliocentric ecliptic
                 coordinates of the Earth referred to the dynamical equinox of date.
                 Source: IMCCE, https://ftp.imcce.fr/pub/ephem/planets/vsop87/VSOP87D.ear
                 Terms with |A| < THRESHOLD are dropped; for 1950–2100 the dropped terms add up
                 to at most 0.48" in longitude, 0.17" in latitude and 290 km in distance.
  moonposition.go — Meeus, "Astronomical Algorithms" (2nd ed.), tables 47.A and 47.B
                 (truncated ELP-2000/82), as transcribed in github.com/soniakeys/meeus
                 (v3/moonposition/moonposition.go, © 2013 Sonia Keys; repository LICENSE © 2018 Sonia Keys, MIT).

Usage: gen_astro_tables.py VSOP87D.ear moonposition.go src/core/astro
"""
import re
import sys
from pathlib import Path

THRESHOLD = 3e-8
# REUSE-IgnoreStart
HEADER = """// SPDX-FileCopyrightText: {copyright}
// SPDX-License-Identifier: {license}
//
// Generated by scripts/data/gen_astro_tables.py — do not edit.
// {source}

"""
# REUSE-IgnoreEnd


def read_vsop(path):
    series = {}
    current = None
    for line in Path(path).read_text().splitlines():
        if "VSOP87" in line:
            variable = int(line.split("VARIABLE")[1].split()[0])
            power = int(line.split("*T**")[1].split()[0])
            current = (variable, power)
            series[current] = []
        elif line.strip():
            fields = line.split()
            series[current].append(tuple(float(x) for x in fields[-3:]))
    return series


def write_vsop(series, out):
    names = {1: "L", 2: "B", 3: "R"}
    lines = [HEADER.format(
        # Converted table distributed under the project's MIT licence, crediting the authors
        # (decision recorded in docs/SPECIFICATION.md §12.4). The tag is split so that REUSE
        # does not read this script's own licence from the string.
        copyright="2026 Juan Maria Gomez Lopez <juan-maria.gomez-lopez@tutamail.com>\n"
                  "// SPDX-" "FileCopyrightText: 1988 P. Bretagnon and G. Francou (VSOP87, IMCCE)",
        license="MIT",
        source="VSOP87D Earth series from IMCCE, truncated to |A| >= %g. Coefficients from\n"
               "// P. Bretagnon and G. Francou, A&A 202, 309 (1988); distributed with this project "
               "under MIT." % THRESHOLD)]
    lines.append('#include "vsop87_earth.hpp"\n\nnamespace ds::astro::detail {\nnamespace {\n')
    index = []
    kept = 0
    for variable in (1, 2, 3):
        for power in range(6):
            terms = [t for t in series.get((variable, power), []) if abs(t[0]) >= THRESHOLD]
            name = f"k{names[variable]}{power}"
            if not terms:
                index.append((variable, power, None, 0))
                continue
            kept += len(terms)
            lines.append(f"constexpr VsopTerm {name}[] = {{")
            for a, b, c in terms:
                lines.append(f"    {{{a!r}, {b!r}, {c!r}}},")
            lines.append("};\n")
            index.append((variable, power, name, len(terms)))
    lines.append("}  // namespace\n")
    for variable in (1, 2, 3):
        entries = []
        for v, power, name, count in index:
            if v != variable:
                continue
            entries.append(f"    std::span<const VsopTerm>({name})" if name else "    std::span<const VsopTerm>()")
        lines.append(f"const std::array<std::span<const VsopTerm>, 6> kEarth{names[variable]}{{")
        lines.append(",\n".join(entries))
        lines.append("};\n")
    lines.append("}  // namespace ds::astro::detail\n")
    (out / "vsop87_earth_data.cpp").write_text("\n".join(lines))
    return kept


def read_go_table(text, name, width):
    body = re.search(r"var %s = \[\.\.\.\]\w+\{(.*?)\n\}" % name, text, re.S).group(1)
    rows = []
    for match in re.finditer(r"\{([^{}]*)\}", body):
        values = [v.strip() for v in match.group(1).split(",")]
        assert len(values) == width, values
        rows.append([int(float(v)) for v in values])
    return rows


def write_moon(go_path, out):
    text = Path(go_path).read_text()
    ta = read_go_table(text, "ta", 6)
    tb = read_go_table(text, "tb", 5)
    assert len(ta) == 60 and len(tb) == 60, (len(ta), len(tb))
    lines = [HEADER.format(
        copyright="2013-2018 Sonia Keys",
        license="MIT",
        source="Meeus, Astronomical Algorithms (2nd ed.), tables 47.A and 47.B, transcribed from "
               "github.com/soniakeys/meeus v3/moonposition (MIT).")]
    lines.append('#include "moon_tables.hpp"\n\nnamespace ds::astro::detail {\n')
    lines.append("// D, M, M', F, Σl (1e-6 deg), Σr (1e-3 km)")
    lines.append("const std::array<MoonLrTerm, 60> kMoonLr{{")
    lines += [f"    {{{r[0]}, {r[1]}, {r[2]}, {r[3]}, {r[4]}, {r[5]}}}," for r in ta]
    lines.append("}};\n")
    lines.append("// D, M, M', F, Σb (1e-6 deg)")
    lines.append("const std::array<MoonBTerm, 60> kMoonB{{")
    lines += [f"    {{{r[0]}, {r[1]}, {r[2]}, {r[3]}, {r[4]}}}," for r in tb]
    lines.append("}};\n")
    lines.append("}  // namespace ds::astro::detail\n")
    (out / "moon_tables_data.cpp").write_text("\n".join(lines))


def main(vsop_path, go_path, out_dir):
    out = Path(out_dir)
    kept = write_vsop(read_vsop(vsop_path), out)
    write_moon(go_path, out)
    print(f"VSOP87D Earth: {kept} terms kept; Moon: 60 + 60 terms")


if __name__ == "__main__":
    main(*sys.argv[1:4])
