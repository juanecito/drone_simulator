"""Generates reference tables for the core/geo unit tests (SPECIFICATION §8.1).

Reference implementations (independent of ours):
  * PROJ (via pyproj): geodetic <-> ECEF, UTM (extended transverse Mercator), EPSG:3857.
  * GeographicLib (Karney): inverse geodesic problem.

Usage:  python3 -m venv .venv && .venv/bin/pip install pyproj geographiclib
        .venv/bin/python scripts/fixtures/gen_geo_fixtures.py tests/fixtures/geo
"""
import csv
import math
import random
import sys
from pathlib import Path

import pyproj
from geographiclib.geodesic import Geodesic

HEADER = ("# Generated by scripts/fixtures/gen_geo_fixtures.py with PROJ {} and GeographicLib {}."
          " Do not edit.\n")


def utm_zone(lat, lon):
    """Standard zone plus the Norway and Svalbard exceptions."""
    lon = ((lon + 180.0) % 360.0) - 180.0
    zone = min(int(math.floor((lon + 180.0) / 6.0)) + 1, 60)
    if 56.0 <= lat < 64.0 and 3.0 <= lon < 12.0:
        return 32
    if lat >= 72.0 and 0.0 <= lon < 42.0:
        return 31 if lon < 9.0 else 33 if lon < 21.0 else 35 if lon < 33.0 else 37
    return zone


def write(path, header, columns, rows):
    with open(path, "w", newline="") as f:
        f.write(header)
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(columns)
        writer.writerows(rows)


def main(out_dir):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rng = random.Random(20261113)
    import geographiclib
    header = HEADER.format(pyproj.proj_version_str, geographiclib.__version__)

    # --- Geodetic -> ECEF ---------------------------------------------------------------
    to_ecef = pyproj.Transformer.from_crs("EPSG:4979", "EPSG:4978", always_xy=True)
    points = [(0, 0, 0), (90, 0, 0), (-90, 0, 0), (0, 180, 0), (45, 45, 1000),
              (40.4168, -3.7038, 667), (-33.8688, 151.2093, 58), (27.9881, 86.9250, 8848.86),
              (-89.9999, 10, 2835), (0.0, -179.9999, -100)]
    points += [(rng.uniform(-90, 90), rng.uniform(-180, 180), rng.uniform(-500, 12000))
               for _ in range(200)]
    rows = []
    for lat, lon, h in points:
        x, y, z = to_ecef.transform(lon, lat, h)
        rows.append([f"{lat:.10f}", f"{lon:.10f}", f"{h:.6f}", f"{x:.6f}", f"{y:.6f}", f"{z:.6f}"])
    write(out / "ecef.csv", header, ["lat_deg", "lon_deg", "h_m", "x_m", "y_m", "z_m"], rows)

    # --- UTM ----------------------------------------------------------------------------
    cases = [(0.0, 3.0), (0.0, -177.0), (0.0, 0.0), (0.0, 5.999999), (0.0, 6.0),
             (40.4168, -3.7038), (-33.8688, 151.2093), (-79.999, 17.0), (83.999, -45.0),
             (84.0, 10.0), (-80.0, -120.0), (60.0, 2.999), (60.0, 3.0), (60.0, 11.999),
             (60.0, 12.0), (55.999, 4.0), (64.0, 4.0), (78.0, 8.999), (78.0, 9.0),
             (78.0, 20.999), (78.0, 21.0), (78.0, 32.999), (78.0, 33.0), (78.0, 41.999),
             (78.0, 42.0), (71.999, 8.0), (-0.000001, 33.0), (0.000001, 33.0), (51.4778, -0.0015)]
    for _ in range(400):
        lat = rng.uniform(-80.0, 84.0)
        lon = rng.uniform(-180.0, 180.0)
        cases.append((lat, lon))
    rows = []
    for lat, lon in cases:
        zone = utm_zone(lat, lon)
        south = lat < 0.0
        crs = pyproj.CRS.from_proj4(
            f"+proj=utm +zone={zone} {'+south ' if south else ''}+datum=WGS84 +units=m +no_defs")
        tr = pyproj.Transformer.from_crs("EPSG:4326", crs, always_xy=True)
        e, n = tr.transform(lon, lat)
        rows.append([f"{lat:.10f}", f"{lon:.10f}", zone, "S" if south else "N",
                     f"{e:.6f}", f"{n:.6f}"])
    write(out / "utm.csv", header,
          ["lat_deg", "lon_deg", "zone", "hemisphere", "easting_m", "northing_m"], rows)

    # --- Web Mercator (EPSG:3857) -------------------------------------------------------
    to_merc = pyproj.Transformer.from_crs("EPSG:4326", "EPSG:3857", always_xy=True)
    rows = []
    for lat, lon in [(0, 0), (51.5074, -0.1278), (-33.8688, 151.2093), (85.0, 179.9),
                     (-85.0, -179.9), (40.4168, -3.7038)]:
        x, y = to_merc.transform(lon, lat)
        rows.append([f"{lat:.10f}", f"{lon:.10f}", f"{x:.6f}", f"{y:.6f}"])
    write(out / "web_mercator.csv", header, ["lat_deg", "lon_deg", "x_m", "y_m"], rows)

    # --- Inverse geodesic ---------------------------------------------------------------
    geod = Geodesic.WGS84
    pairs = [((40.4168, -3.7038), (41.3874, 2.1686)), ((0, 0), (0, 1)), ((0, 0), (1, 0)),
             ((51.5, 0.0), (51.5001, 0.0001)), ((-33.8688, 151.2093), (51.5074, -0.1278)),
             ((89.9, 0), (89.9, 180)), ((10, 10), (10.000001, 10.000001)), ((0, 0), (0, 179))]
    for _ in range(200):
        lat1, lon1 = rng.uniform(-89, 89), rng.uniform(-180, 180)
        if rng.random() < 0.5:   # short ranges, as used by the HUD and missions
            lat2, lon2 = lat1 + rng.uniform(-0.5, 0.5), lon1 + rng.uniform(-0.5, 0.5)
            lat2 = max(-89.9, min(89.9, lat2))
        else:
            lat2, lon2 = rng.uniform(-89, 89), rng.uniform(-180, 180)
        pairs.append(((lat1, lon1), (lat2, lon2)))
    rows = []
    for (lat1, lon1), (lat2, lon2) in pairs:
        r = geod.Inverse(lat1, lon1, lat2, lon2)
        if r["a12"] > 179.0:      # nearly antipodal: Vincenty is not expected to converge
            continue
        rows.append([f"{lat1:.10f}", f"{lon1:.10f}", f"{lat2:.10f}", f"{lon2:.10f}",
                     f"{r['s12']:.6f}", f"{r['azi1'] % 360.0:.9f}", f"{r['azi2'] % 360.0:.9f}"])
    write(out / "geodesic.csv", header,
          ["lat1_deg", "lon1_deg", "lat2_deg", "lon2_deg", "distance_m", "azi1_deg", "azi2_deg"],
          rows)
    print(f"wrote fixtures to {out}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "tests/fixtures/geo")
